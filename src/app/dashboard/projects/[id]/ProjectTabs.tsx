export function ProjectTabs({ projectId }: ProjectTabsProps) {
  const pathname = usePathname();

  const isActive = (tab: typeof tabs[0]) => {
    const tabPath = tab.href(projectId);
    if (tab.exact) {
      return pathname === tabPath;
    }
    return pathname.startsWith(tabPath);
  };

  return (
    <div className="flex items-center gap-1 border-t border-landing-charcoal/5 pt-4 -mb-6 -mx-6 px-6">
      {tabs.map((tab) => {
        const active = isActive(tab);
        return (
          <Link
            key={tab.id}
            href={tab.href(projectId)}
            className={cn(
              "flex items-center gap-2 px-4 py-2.5 text-[11px] uppercase tracking-wider font-medium rounded-t-lg transition-all duration-200 border-b-2",
              active
                ? "bg-landing-ivory text-landing-charcoal border-landing-forest"
                : "text-landing-stone hover:text-landing-charcoal border-transparent hover:bg-landing-charcoal/5"
            )}
          >
            {tab.icon}
            {tab.label}
          </Link>
        );
      })}
    </div>
  );
}
